"""Builder-specific SCAD straight from a vendored turtle_body bundle.

The vendored bundles in generator/turtle_body/scad/ (copied by
sync_from_turtle_body.py) are turtle_body's own self-contained component
files. Every shared dimension in them is a zero-argument `function p_*()`
from turtle_body's lib/params.scad, and every derived value is a function of
those -- so overriding a handful of base `p_*()` literals (bottle diameter,
wood thickness, ...) re-derives the whole component exactly as turtle_body
would, with no hand-copied geometry to drift.

Used by the sail frame (generate_sails.py) and the head fin
(head_fin_generator.py). The older generators (rear fin, ballast, 6FC) still
carry their own SCAD templates.
"""
from __future__ import annotations

import math
import re
from pathlib import Path
from typing import Dict, Union

VENDOR_SCAD = Path(__file__).resolve().parent / "turtle_body" / "scad"

Number = Union[int, float]


def load_bundle(name: str) -> str:
    path = VENDOR_SCAD / name
    if not path.is_file():
        raise FileNotFoundError(
            f"Vendored turtle_body bundle {name} is missing. "
            "Run: python3 generator/sync_from_turtle_body.py"
        )
    return path.read_text(encoding="utf-8")


def _fmt(value: Number) -> str:
    value = float(value)
    if not math.isfinite(value):
        raise ValueError("SCAD override values must be finite")
    return format(value, ".12g")


def override_params(text: str, values: Dict[str, Number]) -> str:
    """Replace the body of each `function p_name() = ...;` with a literal.

    Each name must occur exactly once (the bundle inlines params.scad once);
    anything else means the bundle changed shape and is an error, never a
    silent no-op.
    """
    for name, value in values.items():
        pattern = re.compile(r"^(function\s+" + re.escape(name) + r"\(\)\s*=\s*)[^;]*;", re.M)
        matches = pattern.findall(text)
        if len(matches) != 1:
            raise ValueError(f"Bundle defines {name}() {len(matches)} times; expected exactly 1")
        text = pattern.sub(lambda m: m.group(1) + _fmt(value) + ";", text, count=1)
    return text


def override_customizer(text: str, values: Dict[str, Union[Number, str, bool]]) -> str:
    """Replace a top-level customizer assignment `name = ...;` (the wrapper's
    first occurrence). Strings are quoted, booleans lower-cased."""
    for name, value in values.items():
        if isinstance(value, bool):
            literal = "true" if value else "false"
        elif isinstance(value, str):
            literal = '"' + value.replace('"', "") + '"'
        else:
            literal = _fmt(value)
        pattern = re.compile(r"^(" + re.escape(name) + r"\s*=\s*)[^;]*;", re.M)
        if not pattern.search(text):
            raise ValueError(f"Bundle has no customizer variable {name}")
        text = pattern.sub(lambda m: m.group(1) + literal + ";", text, count=1)
    return text


def stamp(text: str, title: str, inputs: Dict[str, Number]) -> str:
    """Prefix a short provenance header naming the builder's inputs."""
    lines = [f"// {title}", "// Generated by hopeturtles.org/turtles/generate from turtle_body's",
             "// own component bundle, with these base dimensions overridden:"]
    lines += [f"//   {k} = {_fmt(v)}" for k, v in inputs.items()]
    return "\n".join(lines) + "\n" + text
