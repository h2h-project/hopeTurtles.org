def _register_fonts(font_dir: Optional[Path] = None) -> Tuple[str, str, str]:
    """Register preferred fonts, falling back to DejaVu/Helvetica.

    Place fonts here if you want exact site typography:
      ecojoiner/fonts/Arvo-Regular.ttf
      ecojoiner/fonts/Mulish-Light.ttf
      ecojoiner/fonts/Mulish-Regular.ttf

    The fallback DejaVuSans is useful because it supports the diameter symbol.
    """
    if pdfmetrics is None:
        raise RuntimeError("ReportLab is not installed. Install with: pip install reportlab")

    search_dirs = []
    if font_dir:
        search_dirs.append(font_dir)
    search_dirs.extend([
        Path.cwd() / "ecojoiner" / "fonts",
        Path.cwd() / "fonts",
        Path("/usr/share/fonts/truetype/dejavu"),
    ])

    def try_font(font_name: str, filenames: Sequence[str]) -> Optional[str]:
        for directory in search_dirs:
            for filename in filenames:
                p = directory / filename
                if p.exists():
                    pdfmetrics.registerFont(TTFont(font_name, str(p)))
                    return font_name
        return None

    title_font = try_font("ArvoRegular", ["Arvo-Regular.ttf", "Arvo.ttf"])
    body_font = try_font("MulishLight", ["Mulish-Light.ttf", "Mulish-Regular.ttf"])
    mono_font = try_font("DejaVuSans", ["DejaVuSans.ttf"])

    # If preferred fonts are missing, use DejaVuSans so symbols like diameter render.
    fallback = mono_font or "Helvetica"
    return title_font or fallback, body_font or fallback, fallback


def _draw_dimension_line(c, x1, y1, x2, y2, text, font="Helvetica", size=7, offset=0, label_side="right", ext1=None, ext2=None, rotate_label=False):
    """Draw a simple dimension line with arrowheads and a label.

    The label's clearance from the line is computed from the label's own
    rendered width (for vertical lines) so it never visually crosses the
    line it's describing, regardless of how long the text is. `label_side`
    ("right" or "left") picks which side of a vertical line the label sits
    on, since the shape being dimensioned can be on either side of the line.

    `ext1`/`ext2`, when given as (x, y) points, are the actual feature edges
    the dimension line is measuring (the dimension line itself is often
    offset away from the geometry for legibility). A light witness/extension
    line is drawn from each feature edge out to the dimension line's
    endpoint so it is unambiguous what the arrow is pointing to.

    `rotate_label`, for vertical lines only, draws the label rotated 90
    degrees and centered directly on the line instead of offset to one
    side. Use this when the line runs through a narrow feature (like a
    slot) with no clear space beside it for a horizontal label.
    """
    if ext1 is not None or ext2 is not None:
        c.setStrokeColor(colors.HexColor("#cccccc"))
        c.setLineWidth(0.3)
        if ext1 is not None:
            c.line(ext1[0], ext1[1], x1, y1)
        if ext2 is not None:
            c.line(ext2[0], ext2[1], x2, y2)

    c.setStrokeColor(colors.HexColor("#777777"))
    c.setFillColor(colors.HexColor("#333333"))
    c.setLineWidth(0.5)
    c.line(x1, y1, x2, y2)

    # crude arrowheads; good enough for carpenter reference PDF. Scaled down
    # on very short lines (e.g. a small true-scale dimension like the
    # presser's nut-recess depth) so the two arrowheads don't cross over
    # each other and collide with the label text.
    line_len = math.hypot(x2 - x1, y2 - y1)
    ah = min(5, line_len / 3)
    c.setFont(font, size)
    text_w = c.stringWidth(text, font, size)
    if abs(x2 - x1) >= abs(y2 - y1):
        c.line(x1, y1, x1 + ah, y1 + ah / 2)
        c.line(x1, y1, x1 + ah, y1 - ah / 2)
        c.line(x2, y2, x2 - ah, y2 + ah / 2)
        c.line(x2, y2, x2 - ah, y2 - ah / 2)
        tx, ty = (x1 + x2) / 2, y1 + 5 + offset
    elif rotate_label:
        c.line(x1, y1, x1 + ah / 2, y1 + ah)
        c.line(x1, y1, x1 - ah / 2, y1 + ah)
        c.line(x2, y2, x2 + ah / 2, y2 - ah)
        c.line(x2, y2, x2 - ah / 2, y2 - ah)
        c.saveState()
        c.translate((x1 + x2) / 2, (y1 + y2) / 2)
        c.rotate(90)
        c.drawCentredString(0, 0, text)
        c.restoreState()
        return
    else:
        c.line(x1, y1, x1 + ah / 2, y1 + ah)
        c.line(x1, y1, x1 - ah / 2, y1 + ah)
        c.line(x2, y2, x2 + ah / 2, y2 - ah)
        c.line(x2, y2, x2 - ah / 2, y2 - ah)
        gap = text_w / 2 + 6 + offset
        tx = x1 - gap if label_side == "left" else x1 + gap
        ty = (y1 + y2) / 2 - size * 0.32

    c.drawCentredString(tx, ty, text)


def _draw_top_edge_with_gaps(c, x0, y_top, x1, gaps):
    """Draw a horizontal top edge as a set of segments, skipping over `gaps`.

    Each gap is an (start_x, end_x) pair in point coordinates where the slot
    notch is cut into the top edge, so that stretch of the edge is open
    material rather than a closed line.
    """
    segments_start = x0
    for gap_start, gap_end in sorted(gaps):
        if gap_start > segments_start:
            c.line(segments_start, y_top, gap_start, y_top)
        segments_start = max(segments_start, gap_end)
    if segments_start < x1:
        c.line(segments_start, y_top, x1, y_top)


def _rounded_rect_text(c, x, y, w, h, title, lines, title_font, body_font):
    c.setStrokeColor(colors.HexColor("#aaaaaa"))
    c.setFillColor(colors.HexColor("#f8f8f8"))
    c.roundRect(x, y, w, h, 5, fill=1, stroke=1)
    c.setFillColor(colors.HexColor("#222222"))
    c.setFont(title_font, 8)
    c.drawString(x + 8, y + h - 13, title)
    c.setFont(body_font, 6.5)
    yy = y + h - 24
    for line in lines:
        c.drawString(x + 8, yy, line)
        yy -= 9


def write_pdf(path: Path, inputs: EcojoinerInputs, d: EcojoinerDerived, *, font_dir: Optional[Path] = None) -> None:
    """Generate the one-page Letter landscape carpenter reference PDF."""
    if canvas is None:
        raise RuntimeError("ReportLab is not installed. Install with: pip install reportlab")

    title_font, body_font, symbol_font = _register_fonts(font_dir)
    lang = _pdf_lang(inputs)
    safe_title_font = _title_font_for(lang, title_font, body_font)

    page_w, page_h = landscape(letter)  # points
    c = canvas.Canvas(str(path), pagesize=landscape(letter))
    c.setTitle(f"Flatpack Ecojoiner v{DESIGN_VERSION}")

    margin = 28
    title_y = page_h - 34

    # Title and top vision statement.
    c.setFont(title_font, 20)
    c.setFillColor(colors.HexColor("#111111"))
    c.drawString(margin, title_y, f"Flatpack Ecojoiner v{DESIGN_VERSION}")

    para_width = 455  # roughly the width of the Long John drawing below
    style = ParagraphStyle(
        name="vision",
        fontName=body_font,
        fontSize=8.64,  # 20% larger than the original 7.2pt
        leading=10.8,
        textColor=colors.HexColor("#333333"),
    )
    p = Paragraph(html.escape(T(lang, "vision_statement")), style)
    p.wrapOn(c, para_width, 60)
    p.drawOn(c, margin, title_y - 58)  # 10pt more clearance below the title than before

    # Board-thickness banner, sitting above the Input variables box. Called
    # out on its own here (rather than left as a dimension line + arrows on
    # the Long John drawing below) since one banner reads faster than a
    # dimension line the reader has to trace back to a callout.
    thickness_box_h = 22
    thickness_box_gap = 6
    thickness_font_size = 9
    thickness_text = T(lang, "board_thickness", thickness=_ceil_mm(inputs.slat_thickness))
    thickness_text_w = c.stringWidth(thickness_text, safe_title_font, thickness_font_size)
    thickness_box_w = thickness_text_w + 16  # right-aligned to the same edge
    # as the Input variables / Derived dimensions boxes below, but sized to
    # fit its own (longer) sentence rather than sharing their fixed 155pt.
    thickness_box_x = page_w - margin - thickness_box_w

    # Input and derived boxes, kept compact. Shifted down from the page top
    # by the thickness banner's height so the two never overlap.
    box_y = page_h - 92 - thickness_box_h - thickness_box_gap
    input_lines = [
        T(lang, "wood", value=_ceil_mm(inputs.slat_thickness)),
        T(lang, "port_length_line", value=_ceil_mm(d.port_length)),
        T(lang, "bottle_diameter", value=_ceil_mm(inputs.port_height)),
        T(lang, "cap_line", value=_ceil_mm(inputs.cap_diameter)),
        T(lang, "collar_line", value=_ceil_mm(inputs.collar_diameter)),
        T(lang, "fit_clearance_line", value=_ceil_mm(inputs.fit_clearance)),
    ]
    derived_lines = [
        T(lang, "john_dim", length=_ceil_mm(d.john_length), height=_ceil_mm(d.john_height)),
        T(lang, "slot_width_line", value=_ceil_mm(d.slot_width)),
        T(lang, "std_slot_depth_line", value=_ceil_mm(d.standard_slot_depth)),
        T(lang, "master_slot_depth_line", value=_ceil_mm(d.master_slot_depth)),
        T(lang, "final_key_dim", length=_ceil_mm(d.final_key_length), width=_ceil_mm(d.final_key_width)),
        T(lang, "presser_dim", value=_ceil_mm(d.presser_diameter)),
    ]

    thickness_box_y = (box_y - 8) + 76 + thickness_box_gap
    c.setStrokeColor(colors.HexColor("#aaaaaa"))
    c.setFillColor(colors.HexColor("#f8f8f8"))
    c.roundRect(thickness_box_x, thickness_box_y, thickness_box_w, thickness_box_h, 5, fill=1, stroke=1)
    c.setFillColor(colors.HexColor("#111111"))
    c.setFont(safe_title_font, thickness_font_size)
    c.drawCentredString(
        thickness_box_x + thickness_box_w / 2,
        thickness_box_y + thickness_box_h / 2 - 3.5,
        thickness_text,
    )

    _rounded_rect_text(c, page_w - margin - 155, box_y - 8, 155, 76, T(lang, "input_variables_title"), input_lines, safe_title_font, body_font)
    derived_box_x, derived_box_y, derived_box_w = page_w - margin - 155, box_y - 94, 155
    _rounded_rect_text(c, derived_box_x, derived_box_y, derived_box_w, 76, T(lang, "derived_dimensions_title"), derived_lines, safe_title_font, body_font)

    # Notes, placed under the Derived dimensions box rather than at the foot
    # of the page so the John drawings can use the full page height.
    notes_style = ParagraphStyle(
        name="notes",
        fontName=body_font,
        fontSize=6,
        leading=7.4,
        textColor=colors.HexColor("#333333"),
    )
    notes_p = Paragraph(html.escape(T(lang, "notes")), notes_style)
    notes_p.wrapOn(c, derived_box_w, 60)
    notes_p.drawOn(c, derived_box_x, derived_box_y - 10 - notes_p.height)

    # Main drawing area. Scale is chosen to fill the available Letter page
    # space; the PDF is a reference, not a 1:1 tracing template. The SVG
    # export is the 1:1 cut file. The three Johns share one scale (derived
    # from the tallest constraint, vertical space) so they stay comparable,
    # and are spread evenly through the full column height instead of being
    # crammed into a small fixed-size block.
    left_pad = 80  # room for the rotated part title and the overall-height
    # dimension line, stacked to the left of each slat
    draw_x = margin + left_pad
    right_col_x = page_w - margin - 205  # Final Key / Presser column start

    content_top = page_h - 130
    content_bottom = 45  # the footer notes have moved up next to the Derived dimensions box
    n_rows = 3
    row_pitch = (content_top - content_bottom) / n_rows

    # Reserve space above each slat for the port-length/between-notch
    # dimension row and the slot-width dimension line, and below each slat
    # for the side-offset and overall-length dimension lines, so arrows never
    # collide with the geometry or the next row. The part title has moved to
    # a rotated label on the left of the slat, so it no longer needs room
    # above the row.
    top_pad = 30
    bottom_pad = 34
    slat_h_budget = row_pitch - top_pad - bottom_pad

    available_width = right_col_x - draw_x - 20
    scale = min(available_width / d.john_length, slat_h_budget / d.john_height)
    s = scale

    def sx(v): return v * s

    def draw_john(label, row_top, slot_depth, slots, hole_diam):
        x = draw_x
        y_top = row_top - top_pad
        y = y_top - sx(d.john_height)
        x_right = x + sx(d.john_length)
        c.setStrokeColor(colors.black)
        c.setFillColor(colors.white)
        c.setLineWidth(1)

        # Outer profile: bottom, left, and right edges are solid. The top
        # edge is drawn in segments that skip over each slot opening, since
        # the slots are notches cut into the top edge, not closed pockets -
        # a continuous line across them would misleadingly show them as
        # closed.
        c.line(x, y, x_right, y)
        c.line(x, y, x, y_top)
        c.line(x_right, y, x_right, y_top)
        slot_gaps = [
            (x + sx(cx - d.slot_width / 2), x + sx(cx + d.slot_width / 2))
            for cx in slots
        ]
        _draw_top_edge_with_gaps(c, x, y_top, x_right, slot_gaps)

        # Slots: left, right, and bottom only - no top line, since the slot
        # is open into the board's top edge, not a closed pocket.
        for cx in slots:
            slot_left = x + sx(cx - d.slot_width / 2)
            slot_right = x + sx(cx + d.slot_width / 2)
            slot_bottom = y_top - sx(slot_depth)
            c.line(slot_left, y_top, slot_left, slot_bottom)
            c.line(slot_right, y_top, slot_right, slot_bottom)
            c.line(slot_left, slot_bottom, slot_right, slot_bottom)

        # Center hole.
        c.circle(x + sx(d.john_length / 2), y + sx(d.john_height / 2), sx(hole_diam / 2), stroke=1, fill=0)
        c.setFillColor(colors.HexColor("#111111"))
        c.setFont(symbol_font, 9)
        c.drawCentredString(x + sx(d.john_length / 2), y + sx(d.john_height / 2) - 3, f"⌀{_ceil_mm(hole_diam)}")

        # Screw pilot holes. The left hole's label grows rightward and the
        # right hole's label grows leftward, back toward the hole, so
        # neither one runs past the slat's outer edge.
        screw_label = f"M6 (⌀{_ceil_mm(inputs.screw_diameter)}mm)"
        for i, hx in enumerate((d.screw_side_offset, d.john_length - d.screw_side_offset)):
            hcx, hcy = x + sx(hx), y + sx(d.screw_y_center)
            c.circle(hcx, hcy, sx(inputs.screw_diameter / 2), stroke=1, fill=0)
            c.setFillColor(colors.HexColor("#111111"))
            c.setFont(symbol_font, 6.5)
            if i == 0:
                c.drawString(hcx + 7, hcy + 2, screw_label)
            else:
                c.drawRightString(hcx - 7, hcy + 2, screw_label)

        # Part title, rotated 90 degrees and set to the left of the slat
        # rather than above it, so the vertical space above each row is free
        # for the Johns to be spaced comfortably apart.
        c.saveState()
        c.setFillColor(colors.HexColor("#111111"))
        c.setFont(title_font, 11)
        c.translate(x - 58, (y + y_top) / 2)
        c.rotate(90)
        c.drawCentredString(0, 0, label)
        c.restoreState()

        # Dimension lines for port length, the gap between the two notches,
        # slot width/depth, overall height, screw side offset, and overall
        # length, given generous clearance from the geometry so arrowheads,
        # witness lines, and text don't crowd each other or the title.
        slot_cx = slots[0]
        slot_left_mm = slot_cx - d.slot_width / 2
        slot_right_mm = slot_cx + d.slot_width / 2
        slot_left = x + sx(slot_left_mm)
        slot_right = x + sx(slot_right_mm)
        slot_cx_pt = x + sx(slot_cx)

        # Port length: the distance from the slat's side to the start of the
        # first notch. Between-notch span: the gap left between the two
        # notches, which seats the bottle body (its diameter).
        slot2_cx = slots[1]
        slot2_left_mm = slot2_cx - d.slot_width / 2
        port_length_mm = slot_left_mm
        between_notches_mm = slot2_left_mm - slot_right_mm
        slot2_left = x + sx(slot2_left_mm)
        port_row_y = y_top + 26
        _draw_dimension_line(
            c, x, port_row_y, slot_left, port_row_y, T(lang, "port_label", value=_ceil_mm(port_length_mm)), body_font, 6.5,
            ext1=(x, y_top), ext2=(slot_left, y_top),
        )
        _draw_dimension_line(
            c, slot_right, port_row_y, slot2_left, port_row_y, T(lang, "between_notches_label", value=_ceil_mm(between_notches_mm)), body_font, 6.5,
            ext1=(slot_right, y_top), ext2=(slot2_left, y_top),
        )

        _draw_dimension_line(
            c, slot_left, y_top + 9, slot_right, y_top + 9, T(lang, "slot_label", value=_ceil_mm(d.slot_width)), body_font, 6.5,
            ext1=(slot_left, y_top), ext2=(slot_right, y_top),
        )
        _draw_dimension_line(
            c, slot_cx_pt, y_top, slot_cx_pt, y_top - sx(slot_depth), f"{_ceil_mm(slot_depth)}mm", body_font, 6.5, rotate_label=True,
        )
        _draw_dimension_line(
            c, x - 14, y, x - 14, y_top, f"{_ceil_mm(d.john_height)}mm", body_font, 6.5, label_side="left",
            ext1=(x, y), ext2=(x, y_top),
        )
        _draw_dimension_line(
            c, x, y - 11, x + sx(d.screw_side_offset), y - 11, T(lang, "from_side_label"), body_font, 6.5,
            ext1=(x, y), ext2=(x + sx(d.screw_side_offset), y),
        )
        _draw_dimension_line(
            c, x, y - 27, x + sx(d.john_length), y - 27, f"{_ceil_mm(d.john_length)}mm", body_font, 6.5,
            ext1=(x, y), ext2=(x + sx(d.john_length), y),
        )

    long_slots = (d.long_end_span + inputs.slat_thickness / 2, d.john_length - d.long_end_span - inputs.slat_thickness / 2)
    little_slots = (d.little_end_span + inputs.slat_thickness / 2, d.john_length - d.little_end_span - inputs.slat_thickness / 2)

    draw_john("Long John x 6", content_top, d.standard_slot_depth, long_slots, inputs.cap_diameter)
    draw_john("Little John x 5", content_top - row_pitch, d.standard_slot_depth, little_slots, inputs.collar_diameter)
    draw_john("Master John x 1", content_top - 2 * row_pitch, d.master_slot_depth, little_slots, inputs.collar_diameter)

    # Right-side parts: Final Key and Presser. Lowered from the top of their
    # column (they used to sit right under the Derived-dimensions notes,
    # leaving a large empty gap between them and the footer) so they split
    # the column's leftover vertical space more evenly.
    right_x = page_w - margin - 205
    right_y = 170

    c.setFont(title_font, 9)
    c.drawString(right_x, right_y + 118, "Final Key x 4")
    fk_scale = min(1.0, 190 / d.final_key_length)
    c.setStrokeColor(colors.black)
    c.setLineWidth(1)
    c.rect(right_x, right_y + 90, d.final_key_length * fk_scale, d.final_key_width * fk_scale, fill=0, stroke=1)
    _draw_dimension_line(
        c, right_x, right_y + 74, right_x + d.final_key_length * fk_scale, right_y + 74, f"{_ceil_mm(d.final_key_length)}mm", body_font, 5,
        ext1=(right_x, right_y + 90), ext2=(right_x + d.final_key_length * fk_scale, right_y + 90),
    )
    _draw_dimension_line(
        c, right_x - 7, right_y + 90, right_x - 7, right_y + 90 + d.final_key_width * fk_scale, f"{_ceil_mm(d.final_key_width)}mm", body_font, 5, label_side="left",
        ext1=(right_x, right_y + 90), ext2=(right_x, right_y + 90 + d.final_key_width * fk_scale),
    )

    # Presser top view and side/section view directly below it.
    p_top_cx = right_x + 58
    p_top_cy = right_y + 10
    p_r = 22
    c.setFont(title_font, 9)
    c.drawString(right_x, p_top_cy + 46, "Presser x 12")
    c.setStrokeColor(colors.black)
    c.setLineWidth(1)
    c.circle(p_top_cx, p_top_cy, p_r, stroke=1, fill=0)
    c.circle(p_top_cx, p_top_cy, p_r * d.presser_through_hole_diameter / d.presser_diameter, stroke=1, fill=0)
    c.setDash(2, 2)
    c.circle(p_top_cx, p_top_cy, p_r * d.presser_nut_recess_diameter / d.presser_diameter, stroke=1, fill=0)
    c.setDash()
    _draw_dimension_line(
        c, p_top_cx - p_r, p_top_cy - p_r - 8, p_top_cx + p_r, p_top_cy - p_r - 8, f"⌀{_ceil_mm(d.presser_diameter)}mm", body_font, 5,
        ext1=(p_top_cx - p_r, p_top_cy), ext2=(p_top_cx + p_r, p_top_cy),
    )
    c.setFont(body_font, 6)
    c.drawString(p_top_cx + p_r + 12, p_top_cy + 8, T(lang, "through_hole_label", value=_ceil_mm(d.presser_through_hole_diameter)))
    c.drawString(p_top_cx + p_r + 12, p_top_cy - 2, T(lang, "nut_recess_label", diam=_ceil_mm(d.presser_nut_recess_diameter), depth=_ceil_mm(d.presser_nut_recess_depth)))

    # Side/section view under top view. Uses the same points-per-mm scale as
    # the top view (derived from p_r / presser radius) so the two views
    # depict the same physical part at matching sizes - the section's width
    # equals the top view's diameter, and its through-hole/recess widths
    # match the top view's hole/recess circles, rather than being drawn at
    # unrelated fixed sizes.
    presser_scale = p_r / (d.presser_diameter / 2)
    side_w = d.presser_diameter * presser_scale
    side_h = d.presser_thickness * presser_scale
    side_x = p_top_cx - side_w / 2
    side_y = p_top_cy - 62
    c.setStrokeColor(colors.black)
    c.setLineWidth(1)
    c.rect(side_x, side_y, side_w, side_h, fill=0, stroke=1)
    # Through hole in section.
    hole_w = d.presser_through_hole_diameter * presser_scale
    c.rect(p_top_cx - hole_w / 2, side_y, hole_w, side_h, fill=0, stroke=1)
    # Recess from top.
    recess_w = d.presser_nut_recess_diameter * presser_scale
    recess_h = d.presser_nut_recess_depth * presser_scale
    c.rect(p_top_cx - recess_w / 2, side_y + side_h - recess_h, recess_w, recess_h, fill=0, stroke=1)
    _draw_dimension_line(
        c, side_x + side_w + 24, side_y, side_x + side_w + 24, side_y + side_h, f"{_ceil_mm(d.presser_thickness)}mm", body_font, 5,
        ext1=(side_x + side_w, side_y), ext2=(side_x + side_w, side_y + side_h),
    )
    _draw_dimension_line(
        c, p_top_cx + recess_w / 2 + 6, side_y + side_h - recess_h, p_top_cx + recess_w / 2 + 6, side_y + side_h, f"{_ceil_mm(d.presser_nut_recess_depth)}mm", body_font, 5,
        ext1=(p_top_cx + recess_w / 2, side_y + side_h - recess_h), ext2=(p_top_cx + recess_w / 2, side_y + side_h),
    )

    # Credit box, sized to hug its two lines of text rather than leaving a
    # tall band of empty space below them (the box used to be 44pt tall for
    # ~20pt of actual text).
    credit_h = 32
    credit_line2_y = 15
    credit_line1_y = credit_line2_y + 11
