def write_scad(path: Path, inputs: EcojoinerInputs, d: EcojoinerDerived) -> None:
    """Write a self-contained OpenSCAD file.

    This generated SCAD does not require a separate ecojoiner_core.scad file,
    which makes it better for user downloads. Your backend may still keep a
    separate core file for maintenance, but downloadable SCAD should be portable.
    """

    scad = f'''/*
  Flatpack Ecojoiner v{DESIGN_VERSION} - autogenerated
  License: {LICENSE_ID}

  Parts:
    Long John x 6
    Little John x 5
    Master John x 1
    Final Key x 4
    Presser x 12

  Generated from bottle/wood form inputs.
*/

$fn = 96;

// ---------- Input variables ----------
slat_thickness = {inputs.slat_thickness:.3f};
port_length = {d.port_length:.3f};
port_height = {inputs.port_height:.3f};  // bottle diameter
cap_diameter = {inputs.cap_diameter:.3f};
collar_diameter = {inputs.collar_diameter:.3f};
screw_diameter = {inputs.screw_diameter:.3f};  // M6 pilot hole cut diameter
fit_clearance = {inputs.fit_clearance:.3f};

// ---------- Display/export controls ----------
part = "layout";       // layout, full_set, long_john, little_john, master_john, final_key, presser
output_mode = "solid_3d"; // solid_3d or cut_2d
show_labels = true;
layout_gap = 24;
label_size = 7;
label_depth = 0.6;

// ---------- Derived dimensions ----------
john_height = port_height - 2 * slat_thickness;
john_length = 2 * port_length + port_height + 4 * slat_thickness;
slot_width = slat_thickness + fit_clearance;
standard_slot_depth = ceil(john_height / 2);
master_slot_depth = floor(port_height / 2);
long_end_span = port_length;
long_center_span = port_height + 2 * slat_thickness;
little_end_span = port_length + slat_thickness;
little_center_span = port_height;
screw_side_offset = 25;
screw_y_center = john_height / 2;
final_key_length = port_height + 4 * slat_thickness;
final_key_width = 2 * slat_thickness;
presser_diameter = max(1, cap_diameter - 1);
presser_through_hole_diameter = screw_diameter;
presser_nut_recess_diameter = 10;
presser_nut_recess_depth = 5;

// ---------- Safety checks ----------
assert(slat_thickness >= 3 && slat_thickness <= 30, "slat_thickness out of range");
assert(port_length >= 20 && port_length <= 200, "port_length out of range");
assert(port_height >= 30 && port_height <= 200, "port_height out of range");
assert(cap_diameter >= 10 && cap_diameter <= 80, "cap_diameter out of range");
assert(collar_diameter >= 10 && collar_diameter <= 90, "collar_diameter out of range");
assert(screw_diameter >= 3 && screw_diameter <= 12, "screw_diameter out of range");
assert(fit_clearance >= 0 && fit_clearance <= 2, "fit_clearance out of range");
assert(john_height > 0, "Bottle diameter must be greater than twice the wood thickness");
assert(cap_diameter < john_height, "Cap hole too large for John height");
assert(collar_diameter < john_height, "Collar hole too large for John height");

// ---------- Helper modules ----------
module maybe_extrude() {{
  if (output_mode == "cut_2d") children();
  else linear_extrude(height=slat_thickness) children();
}}

module top_slot(center_x, depth) {{
  translate([center_x - slot_width / 2, john_height - depth])
    square([slot_width, depth + 1], center=false);
}}

module center_hole(diameter) {{
  translate([john_length / 2, john_height / 2]) circle(d=diameter);
}}

module screw_holes_2d() {{
  translate([screw_side_offset, screw_y_center]) circle(d=screw_diameter);
  translate([john_length - screw_side_offset, screw_y_center]) circle(d=screw_diameter);
}}

module part_label(txt, w, h) {{
  if (show_labels && output_mode != "cut_2d")
    translate([w / 2, -label_size * 1.4, slat_thickness])
      linear_extrude(height=label_depth)
        text(txt, size=label_size, halign="center", valign="center");
}}

// ---------- 2D profiles ----------
module long_john_2d() {{
  difference() {{
    square([john_length, john_height], center=false);
    top_slot(long_end_span + slat_thickness / 2, standard_slot_depth);
    top_slot(john_length - long_end_span - slat_thickness / 2, standard_slot_depth);
    center_hole(cap_diameter);
    screw_holes_2d();
  }}
}}

module little_john_2d() {{
  difference() {{
    square([john_length, john_height], center=false);
    top_slot(little_end_span + slat_thickness / 2, standard_slot_depth);
    top_slot(john_length - little_end_span - slat_thickness / 2, standard_slot_depth);
    center_hole(collar_diameter);
    screw_holes_2d();
  }}
}}

module master_john_2d() {{
  difference() {{
    square([john_length, john_height], center=false);
    top_slot(little_end_span + slat_thickness / 2, master_slot_depth);
    top_slot(john_length - little_end_span - slat_thickness / 2, master_slot_depth);
    center_hole(collar_diameter);
    screw_holes_2d();
  }}
}}

module final_key_2d() {{
  square([final_key_length, final_key_width], center=false);
}}

module presser_2d() {{
  // Cutting view: outer circle and through pilot hole.
  difference() {{
    circle(d=presser_diameter);
    circle(d=presser_through_hole_diameter);
  }}
  // Nut recess is not a through-cut. It is shown as a faint reference circle.
  %circle(d=presser_nut_recess_diameter);
}}

// ---------- 3D parts ----------
module long_john() {{ maybe_extrude() long_john_2d(); part_label("Long John x 6", john_length, john_height); }}
module little_john() {{ maybe_extrude() little_john_2d(); part_label("Little John x 5", john_length, john_height); }}
module master_john() {{ maybe_extrude() master_john_2d(); part_label("Master John x 1", john_length, john_height); }}
module final_key() {{ maybe_extrude() final_key_2d(); part_label("Final Key x 4", final_key_length, final_key_width); }}

module presser() {{
  if (output_mode == "cut_2d") {{
    presser_2d();
  }} else {{
    // 3D view with through hole and top nut recess.
    difference() {{
      cylinder(d=presser_diameter, h=slat_thickness);
      translate([0,0,-0.1]) cylinder(d=presser_through_hole_diameter, h=slat_thickness + 0.2);
      translate([0,0,slat_thickness - presser_nut_recess_depth])
        cylinder(d=presser_nut_recess_diameter, h=presser_nut_recess_depth + 0.1);
    }}
    part_label("Presser x 12", presser_diameter, presser_diameter);
  }}
}}

// ---------- Layouts ----------
module one_each_layout() {{
  translate([0, 0, 0]) long_john();
  translate([0, -(john_height + layout_gap), 0]) little_john();
  translate([0, -2 * (john_height + layout_gap), 0]) master_john();
  translate([john_length + layout_gap, 0, 0]) final_key();
  translate([john_length + layout_gap + presser_diameter / 2, -(final_key_width + layout_gap + presser_diameter / 2), 0]) presser();
}}

module full_set_layout() {{
  row = john_height + layout_gap;
  for (i = [0:5]) translate([0, -i * row, 0]) long_john();
  for (i = [0:4]) translate([0, -(6+i) * row, 0]) little_john();
  translate([0, -11 * row, 0]) master_john();

  key_y = -12 * row;
  for (i = [0:3]) translate([i * (final_key_length + layout_gap), key_y, 0]) final_key();

  press_y = key_y - final_key_width - layout_gap - presser_diameter / 2;
  for (i = [0:11]) translate([presser_diameter/2 + i * (presser_diameter + layout_gap/2), press_y, 0]) presser();
}}

if (part == "layout") one_each_layout();
else if (part == "full_set") full_set_layout();
else if (part == "long_john") long_john();
else if (part == "little_john") little_john();
else if (part == "master_john") master_john();
else if (part == "final_key") final_key();
else if (part == "presser") presser();
else one_each_layout();
'''

    path.write_text(scad, encoding="utf-8")


