def _to_float(value, default: Optional[float] = None) -> Optional[float]:
    """Convert form values to float while tolerating empty strings."""
    if value is None or value == "":
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        raise ValueError(f"Expected a number, got {value!r}")


def _slugify(text: str, fallback: str = "generic") -> str:
    """Create a safe filename slug from user-provided brand text."""
    text = (text or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = text.strip("-")
    return text or fallback


def parse_inputs_from_dict(data: Dict[str, object]) -> EcojoinerInputs:
    """Parse frontend POST/JSON data into EcojoinerInputs.

    This function accepts both camelCase names used in JS forms and snake_case
    names used by Python/SCAD. That makes it easier to wire into different
    backend frameworks.
    """

    def get(*names, default=None):
        for name in names:
            if name in data:
                return data[name]
        return default

    raw_formats = get("formats", "exportFormats", default=("pdf", "scad", "svg"))
    if isinstance(raw_formats, str):
        # Works for comma-separated values from JSON or a single checkbox value.
        formats = tuple(x.strip().lower() for x in raw_formats.split(",") if x.strip())
    elif isinstance(raw_formats, Iterable):
        formats = tuple(str(x).strip().lower() for x in raw_formats if str(x).strip())
    else:
        formats = ("pdf", "scad", "svg")

    return EcojoinerInputs(
        slat_thickness=_to_float(get("slatThickness", "slat_thickness"), 12.0),
        cap_diameter=_to_float(get("capDiameter", "cap_diameter"), 32.0),
        collar_diameter=_to_float(get("collarDiameter", "collar_diameter"), 32.0),
        taper_height=_to_float(get("taperHeight", "taper_height"), None),
        port_length=_to_float(get("portLength", "port_length"), None),
        port_allowance=_to_float(get("portAllowance", "port_allowance"), DEFAULT_PORT_ALLOWANCE_MM),
        port_height=_to_float(get("portHeight", "port_height", "bottleDiameter", "bottle_diameter"), 85.0)
        + _to_float(get("portFitMm", "port_fit_mm"), 0.0),
        bottle_volume_l=_to_float(get("bottleVolumeL", "bottle_volume_l", "volume", "bottleVolume"), 1.5),
        bottle_brand=str(get("bottleBrand", "bottle_brand", "brand", default="generic") or "generic"),
        screw_diameter=_to_float(get("screwDiameter", "screw_diameter"), 4.5),
        fit_clearance=_to_float(get("fitClearance", "fit_clearance"), 0.20),
        formats=formats,
        job_id=str(get("jobId", "job_id", default="") or ""),
        lang=str(get("lang", default="en") or "en").lower(),
    )


def validate_inputs(inputs: EcojoinerInputs) -> List[str]:
    """Return a list of validation errors. Empty list means OK."""

    errors: List[str] = []

    # Calculate port_length for validation.
    port_length = inputs.port_length
    if port_length is None:
        if inputs.taper_height is None:
            errors.append("Provide either port_length or taper_height.")
            port_length = 0
        else:
            port_length = inputs.taper_height + inputs.port_allowance

    def in_range(label: str, value: float, low: float, high: float, unit: str = "mm"):
        if value < low or value > high:
            errors.append(f"{label} must be between {low:g} and {high:g} {unit}.")

    in_range("Wood thickness", inputs.slat_thickness, 3, 30)
    in_range("Port length", port_length, 20, 200)
    in_range("Bottle diameter / port height", inputs.port_height, 30, 200)
    in_range("Cap diameter", inputs.cap_diameter, 10, 80)
    in_range("Collar diameter", inputs.collar_diameter, 10, 90)
    in_range("Screw pilot-hole diameter", inputs.screw_diameter, 3, 12)
    in_range("Fit clearance", inputs.fit_clearance, 0, 2)

    if inputs.bottle_volume_l <= 0 or inputs.bottle_volume_l > 5:
        errors.append("Bottle volume must be greater than 0L and no more than 5L.")

    # Geometry-specific sanity checks.
    john_height = inputs.port_height - 2 * inputs.slat_thickness
    if john_height <= 0:
        errors.append("Bottle diameter must be greater than twice the wood thickness.")
    else:
        # Keep real material around cap/collar holes. This is a practical
        # woodworking safety margin, not a mathematical requirement.
        min_material_mm = 4.0
        if inputs.cap_diameter >= john_height:
            errors.append("Cap hole is too large for the calculated John slat height.")
        if inputs.collar_diameter >= john_height:
            errors.append("Collar hole is too large for the calculated John slat height.")
        if inputs.screw_diameter >= john_height:
            errors.append("Screw pilot hole is too large for the calculated John slat height.")
        if (john_height - inputs.cap_diameter) / 2 < min_material_mm:
            errors.append("Cap hole leaves less than 4mm of material above/below the hole.")
        if (john_height - inputs.collar_diameter) / 2 < min_material_mm:
            errors.append("Collar hole leaves less than 4mm of material above/below the hole.")

    allowed_formats = {"pdf", "scad", "svg", "dxf"}
    unknown_formats = [f for f in inputs.formats if f not in allowed_formats]
    if unknown_formats:
        errors.append(
            "Unsupported export format(s): " + ", ".join(unknown_formats) +
            ". This Python generator currently supports pdf, scad, svg, and dxf."
        )

    return errors


def derive_dimensions(inputs: EcojoinerInputs) -> EcojoinerDerived:
    """Calculate all geometry from user inputs.

    These formulas are the backbone of the Ecojoiner generator and should stay
    in sync with the OpenSCAD core module used by the website.
    """

    port_length = inputs.port_length
    if port_length is None:
        if inputs.taper_height is None:
            raise ValueError("Cannot derive port_length without taper_height.")
        port_length = inputs.taper_height + inputs.port_allowance

    slat = inputs.slat_thickness
    port_height = inputs.port_height

    john_height = port_height - 2 * slat
    john_length = 2 * port_length + port_height + 4 * slat
    slot_width = slat + inputs.fit_clearance

    # In the Johns, slots are cut downward from the top edge.
    standard_slot_depth = math.ceil(john_height / 2)
    master_slot_depth = math.floor(port_height / 2)

    # Internal spans for Long John vs Little/Master John.
    long_end_span = port_length
    long_center_span = port_height + 2 * slat
    little_end_span = port_length + slat
    little_center_span = port_height

    # M6 pilot holes: centered vertically, fixed 25mm from side edges.
    screw_side_offset = 25.0
    screw_y_center = john_height / 2

    # Final Keys replace Saddlers in v3.2.
    final_key_length = port_height + 4 * slat
    final_key_width = 2 * slat

    # Presser: remnant from cap hole, allowing about 1mm saw/kerf loss.
    # For a 32mm cap hole, this gives the familiar 31mm Presser.
    presser_diameter = max(1.0, inputs.cap_diameter - 1.0)

    return EcojoinerDerived(
        port_length=port_length,
        john_length=john_length,
        john_height=john_height,
        slot_width=slot_width,
        standard_slot_depth=standard_slot_depth,
        master_slot_depth=master_slot_depth,
        long_end_span=long_end_span,
        long_center_span=long_center_span,
        little_end_span=little_end_span,
        little_center_span=little_center_span,
        screw_side_offset=screw_side_offset,
        screw_y_center=screw_y_center,
        final_key_length=final_key_length,
        final_key_width=final_key_width,
        presser_diameter=presser_diameter,
        presser_thickness=slat,
        presser_through_hole_diameter=inputs.screw_diameter,
        presser_nut_recess_diameter=10.0,
        presser_nut_recess_depth=5.0,
    )


def make_job_slug(inputs: EcojoinerInputs, derived: EcojoinerDerived) -> str:
    """Return ecojoiner_<brand>_<volume>L_<johnLength>x<johnHeight>_<jobId>."""
    brand = _slugify(inputs.bottle_brand)
    volume = str(inputs.bottle_volume_l).replace(".", "p")
    job_id = _slugify(inputs.job_id or uuid.uuid4().hex[:8], fallback=uuid.uuid4().hex[:8])
    return (
        f"ecojoiner_{brand}_{volume}L_"
        f"{round(derived.john_length):g}x{round(derived.john_height):g}_{job_id}"
    )


