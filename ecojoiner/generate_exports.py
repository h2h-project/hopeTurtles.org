@dataclass(frozen=True)
class EcojoinerInputs:
    """Raw values collected from the frontend form, after parsing.

    Field mapping from the current frontend form:
      - wood thickness -> slat_thickness
      - bottle cap diameter -> cap_diameter
      - bottle collar diameter -> collar_diameter
      - bottle taper height -> taper_height
      - bottle diameter -> port_height
      - bottle volume -> bottle_volume_l
      - bottle brand -> bottle_brand
      - selected formats -> formats

    The backend may provide port_length directly. If port_length is omitted,
    this script calculates it as:
        port_length = taper_height + port_allowance

    port_height already has the "Adjust Connection" fit offset folded in by
    parse_inputs_from_dict() / main() — see port_fit_mm there. Nothing past
    parsing needs to know about the offset separately; it's just a tighter
    (or looser) port_height.
    """

    slat_thickness: float = 12.0
    cap_diameter: float = 32.0
    collar_diameter: float = 32.0
    taper_height: Optional[float] = 60.0
    port_length: Optional[float] = None
    port_allowance: float = DEFAULT_PORT_ALLOWANCE_MM
    port_height: float = 85.0  # bottle body diameter
    bottle_volume_l: float = 1.5
    bottle_brand: str = "generic"
    screw_diameter: float = 4.5  # physical pilot-hole diameter
    screw_label: str = "M6 (diameter 4.5mm)"
    fit_clearance: float = 0.20
    formats: Tuple[str, ...] = ("pdf", "scad", "svg")
    job_id: str = ""
    lang: str = "en"  # site language; see PDF_STRINGS/_pdf_lang for supported codes


