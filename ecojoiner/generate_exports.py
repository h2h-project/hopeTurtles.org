#!/usr/bin/env python3
"""
Ecojoiner v3.2 export generator
================================

Generates backend-ready Ecojoiner files from bottle + wood measurements:
  - Letter landscape PDF carpenter sheet
  - Self-contained OpenSCAD .scad file
  - 1:1 SVG cutting files
  - 1:1 DXF cutting files
  - JSON manifest with inputs, derived dimensions, and exported file paths

Current design logic: Flatpack Ecojoiner v3.2
  - Long John x 6
  - Little John x 5
  - Master John x 1
  - Final Key x 4
  - Presser x 12

Important design notes:
  - Saddlers have been removed and replaced by four Final Keys.
  - John's central holes are all the same diameter by default. The script still
    accepts cap_diameter and collar_diameter because the form collects both.
  - John screw holes are M6 pilot holes: cut as diameter 4.5mm so the screw
    thread can bite into wood.
  - Pressers use a through M6 pilot hole, plus a top nut recess:
      * through hole: diameter 4.5mm through
      * nut recess: diameter 10mm x 5mm deep

Expected backend usage:
  1. Receive POST fields from /ecojoiners/generate.
  2. Pass the values into this script as CLI args or import this module.
  3. Save generated files under public/ecojoiner_exports/<job-slug>/.
  4. Return download URLs to the frontend.

This file is intentionally verbose and well-commented so it can be adapted
cleanly into an Express, Nuxt/Nitro, Flask, FastAPI, or other backend.
"""

